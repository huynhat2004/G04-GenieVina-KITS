-- PostgreSQL 14+. Apply once to an empty database.
BEGIN;
CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    country VARCHAR(2) NOT NULL CHECK (country ~ '^[A-Z]{2}$'),
    signup_method VARCHAR(20) NOT NULL CHECK (signup_method IN ('EMAIL', 'GOOGLE', 'MICROSOFT')),
    signed_up_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(200) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'OPERATOR', 'VIEWER')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX members_email_unique ON members (LOWER(email));
CREATE TABLE revoked_tokens (
    token_hash VARCHAR(64) PRIMARY KEY,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX revoked_tokens_expiry_idx ON revoked_tokens(expires_at);
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    package_name VARCHAR(100) NOT NULL,
    amount NUMERIC(18,2) NOT NULL CHECK (amount > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'REFUNDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at TIMESTAMPTZ,
    refunded_at TIMESTAMPTZ,
    CONSTRAINT orders_payment_times CHECK (
        (status IN ('PENDING', 'FAILED') AND paid_at IS NULL AND refunded_at IS NULL)
        OR (status = 'PAID' AND paid_at IS NOT NULL AND refunded_at IS NULL)
        OR (status = 'REFUNDED' AND paid_at IS NOT NULL AND refunded_at IS NOT NULL)
    ),
    CHECK (paid_at IS NULL OR paid_at >= created_at),
    CHECK (refunded_at IS NULL OR refunded_at >= paid_at)
);
CREATE TABLE ai_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    type VARCHAR(20) NOT NULL CHECK (type IN ('QUOTE', 'WEBSITE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE order_status_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    previous_status VARCHAR(20) NOT NULL,
    new_status VARCHAR(20) NOT NULL,
    changed_by BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    reason TEXT NOT NULL CHECK (LENGTH(TRIM(reason)) > 0),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((previous_status = 'PENDING' AND new_status IN ('PAID', 'FAILED'))
        OR (previous_status = 'PAID' AND new_status = 'REFUNDED'))
);
CREATE INDEX customers_signed_up_at_idx ON customers(signed_up_at);
CREATE INDEX orders_customer_idx ON orders(customer_id);
CREATE INDEX orders_customer_paid_at_idx ON orders(customer_id, paid_at) WHERE status = 'PAID';
CREATE INDEX orders_paid_at_idx ON orders(paid_at) WHERE status = 'PAID';
CREATE INDEX orders_refunded_at_idx ON orders(refunded_at) WHERE refunded_at IS NOT NULL;
CREATE INDEX ai_results_customer_created_at_idx ON ai_results(customer_id, created_at);
CREATE INDEX order_history_order_time_idx ON order_status_histories(order_id, changed_at, id);
CREATE INDEX order_history_member_idx ON order_status_histories(changed_by);

CREATE FUNCTION validate_customer_event() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE signup_time TIMESTAMPTZ;
BEGIN
    SELECT signed_up_at INTO signup_time FROM customers WHERE id = NEW.customer_id FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Customer % does not exist', NEW.customer_id USING ERRCODE = '23503';
    END IF;
    IF NEW.created_at < signup_time THEN
        RAISE EXCEPTION 'Event cannot precede customer signup' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER orders_validate_customer BEFORE INSERT OR UPDATE ON orders
    FOR EACH ROW EXECUTE FUNCTION validate_customer_event();
CREATE TRIGGER ai_results_validate_customer BEFORE INSERT OR UPDATE ON ai_results
    FOR EACH ROW EXECUTE FUNCTION validate_customer_event();

CREATE FUNCTION protect_signup_date() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.signed_up_at > OLD.signed_up_at AND (
        EXISTS (SELECT 1 FROM orders WHERE customer_id = OLD.id AND created_at < NEW.signed_up_at)
        OR EXISTS (SELECT 1 FROM ai_results WHERE customer_id = OLD.id AND created_at < NEW.signed_up_at)
    ) THEN
        RAISE EXCEPTION 'Signup date cannot follow existing events' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER customers_protect_signup BEFORE UPDATE OF signed_up_at ON customers
    FOR EACH ROW EXECUTE FUNCTION protect_signup_date();

CREATE FUNCTION enforce_order_transition() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'PENDING' THEN
            RAISE EXCEPTION 'New orders must start as PENDING' USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.customer_id IS DISTINCT FROM OLD.customer_id OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Order customer and creation time are immutable' USING ERRCODE = '23514';
    END IF;
    IF OLD.paid_at IS NOT NULL AND NEW.paid_at IS DISTINCT FROM OLD.paid_at THEN
        RAISE EXCEPTION 'Existing payment time is immutable' USING ERRCODE = '23514';
    END IF;
    IF OLD.refunded_at IS NOT NULL AND NEW.refunded_at IS DISTINCT FROM OLD.refunded_at THEN
        RAISE EXCEPTION 'Existing refund time is immutable' USING ERRCODE = '23514';
    END IF;
    IF NEW.status IS DISTINCT FROM OLD.status AND NOT (
        (OLD.status = 'PENDING' AND NEW.status IN ('PAID', 'FAILED'))
        OR (OLD.status = 'PAID' AND NEW.status = 'REFUNDED')
    ) THEN
        RAISE EXCEPTION 'Invalid order transition: % -> %', OLD.status, NEW.status USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER orders_enforce_transition BEFORE INSERT OR UPDATE ON orders
    FOR EACH ROW EXECUTE FUNCTION enforce_order_transition();

CREATE FUNCTION record_order_transition() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE actor BIGINT; change_reason TEXT;
BEGIN
    actor := NULLIF(current_setting('app.member_id', true), '')::BIGINT;
    change_reason := NULLIF(TRIM(current_setting('app.change_reason', true)), '');
    IF actor IS NULL OR change_reason IS NULL THEN
        RAISE EXCEPTION 'Set app.member_id and app.change_reason before changing status' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM members WHERE id = actor AND role IN ('ADMIN', 'OPERATOR')) THEN
        RAISE EXCEPTION 'Actor must be an ADMIN or OPERATOR' USING ERRCODE = '23514';
    END IF;
    INSERT INTO order_status_histories(order_id, previous_status, new_status, changed_by, reason)
        VALUES (NEW.id, OLD.status, NEW.status, actor, change_reason);
    RETURN NEW;
END;
$$;
CREATE TRIGGER orders_record_transition AFTER UPDATE OF status ON orders
    FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
    EXECUTE FUNCTION record_order_transition();
COMMIT;
